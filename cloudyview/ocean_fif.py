"""The moving sea: an (x, y, t) FIF, periodic in all three.

One space-time multifractal is the whole wind sea. It is generated by
scaleinvariance.FIF_ND on an (N, N, NT) grid with Generalized Scale
Invariance putting time on the anisotropic axis at Hz = 1/2: a feature of
size L lives for a time proportional to sqrt(L), which is the deep-water
dispersion relation (omega^2 = g k, period sqrt(2 pi L / g)) read as a
statement about how long a structure of that size lasts. The spheroscale is
set so that a structure lives LIFE_PERIODS of its own wave period.

A cascade that only evolves in place boils; water travels. So each frame's
spatial spectrum is then carried downwind by the dispersion relation itself —
every Fourier mode advances its phase at omega = sqrt(g k), with omega
rounded to a whole number of cycles per loop so the sea is still exactly
periodic in time. The cascade decides where the steep, intermittent patches
are and how they come and go; the phase carries them the way water carries
waves. A cos^2s spreading about the wind axis gives crests their length,
and a spectral peak at the dominant wave (PEAK_*) gives the sea its crests.

Three channels come out, plus a fourth derived one:

  slope   d(height)/dx, d(height)/dy — spectral derivatives, exact and
          periodic. Linear, so a box-filtered mip level is the footprint's
          mean slope, which is what the shader's microfacet lobe wants.
  foam    whitecap potential, rank-shaped: in every frame the steepest
          crest texels (the breaking source, with a decaying residual-foam
          trail behind it) are ranked, and the top FOAM_MAX_COVERAGE of the
          tile is spread uniformly over (0, 1], everything else 0. A cut at
          1 - g therefore keeps exactly g * FOAM_MAX_COVERAGE of the tile in
          every frame, which is what lets the shader gate whitecaps by the
          swell and still know the far-field coverage exactly.
  crest   height above a ~6 m low-pass, positive part, normalized — how
          much thin water a crest holds up for sunlight to shine through
          (the subsurface glow). Linear in the shader, so it mips honestly.

Everything is seeded: a re-run reproduces the same bytes.
"""
import numpy as np
import scaleinvariance
from scaleinvariance.simulation.FIF import extremal_levy

G = 9.81

N = 256                 # texels per side
DX_M = 0.4              # tile 102.4 m, as the static tile before it
NT = 128                # frames per loop
DT_S = 0.2              # loop 25.6 s
H = 0.9                 # height roughness: near the Phillips saturation range
# Nearly Gaussian, as the sea is: at alpha 1.8 or C1 0.01 and up, one Levy
# burst held most of the tile's slope variance and the rest lay flat. Mild
# lognormal intermittency still clusters the steepest crests into groups,
# which is where the whitecaps come from.
ALPHA = 2.0
C1 = 0.005
# How many of its own wave periods a structure of size L lives. Sets the GSI
# spheroscale; see _spheroscale.
LIFE_PERIODS = 3.0
# cos^2s directional spreading about the wind axis.
SPREAD_S = 2.0
# The spectral peak. A cascade is scale-free and a wind sea is not: its
# energy sits at the dominant wave, with little below that wavenumber, and
# that peak is what draws crests. The FIF's spectrum is rolled off below
# k_p and lifted by a JONSWAP-style enhancement about it: an amplitude
# factor over a Gaussian in wavenumber (relative width) and in direction off
# the wind axis (degrees) — the dominant waves are the long-crested,
# well-aligned part of a sea, and without the directional narrowing the peak
# draws no rows. 12 m is a young sea under a moderate breeze and close to
# where the static tile put its dominant waves (10 m).
PEAK_WAVELENGTH_M = 12.0
PEAK_ENHANCEMENT = 4.0
PEAK_WIDTH = 0.15
PEAK_HEADING_DEG = 22.0
# RMS slope of the resolved sea (both axes). The static tile resolved 0.0908
# at 0.2 m; its own mip table put 5% of that variance in the finest octave,
# so the same sea resolved at 0.4 m is 0.088.
RMS_SLOPE = 0.088
# Crest = height above this low-pass, positive part.
CREST_LOWPASS_M = 6.0
# The top fraction of the tile that can carry foam at a full gate; the swell
# gate (raymarch.wgsl) halves it on average.
FOAM_MAX_COVERAGE = 0.02
# Residual foam decays over a couple of seconds after the crest has moved on.
FOAM_DECAY_S = 2.0
# The breaking source: slope above this multiple of the tile's RMS slope, on
# a crest.
BREAKING_SLOPE_RMS = 2.5
# Wind along +x of the tile frame; raymarch.wgsl's swell trains are chosen
# about the same axis.


def _spheroscale(dx_m: float, dt_s: float, life_periods: float) -> float:
    """The GSI spheroscale that makes a time lag of j frames 'the same size' as
    the spatial scale whose wave period, times `life_periods`, is j frames.

    canonical_scale_metric works in half-cells (spacing 2), with the time
    axis entering as ls * (2 j / ls)^(1/Hz) = 4 j^2 / ls at Hz = 1/2. Setting
    that equal to 2 L (L in cells) with j = life * sqrt(2 pi L dx / g) / dt
    gives ls = life^2 * 4 pi dx / (g dt^2), independent of L — which is the
    point of choosing Hz = 1/2.
    """
    return life_periods ** 2 * 4.0 * np.pi * dx_m / (G * dt_s * dt_s)


def generate_sea(seed: int, n: int = N, nt: int = NT, dx_m: float = DX_M,
                 dt_s: float = DT_S, verbose: bool = True) -> dict:
    """Return the sea's channels, each float32 of shape (nt, n, n) = [t, y, x].

    Keys: slope_x, slope_y, foam, crest. Also `height` (not shipped; the
    exporter and tests read it for statistics).
    """
    scaleinvariance.set_numerical_precision('float32')
    period_s = nt * dt_s
    if verbose:
        print(f"  sea FIF: {n}x{n}x{nt} at {dx_m} m / {dt_s} s "
              f"(tile {n * dx_m:.1f} m, loop {period_s:.1f} s) "
              f"alpha={ALPHA} C1={C1} H={H}")

    # The noise is drawn here and handed in: FIF_ND left to itself draws its
    # own, and the seed would describe nothing (the 2026-08-05 bug).
    ls = _spheroscale(dx_m, dt_s, LIFE_PERIODS)
    metric = scaleinvariance.canonical_scale_metric((n, n, nt), ls=ls, Hz=0.5)
    levy = extremal_levy(ALPHA, size=n * n * nt, seed=seed).reshape(n, n, nt)
    f = scaleinvariance.FIF_ND(
        size=(n, n, nt), alpha=ALPHA, C1=C1, H=H, levy_noise=levy,
        periodic=True, scale_metric=metric, elliptical_dim=2.5,
        kernel_construction_method_observable='LS2010',
    )
    # FIF axes are (y, x, t); the texture wants [t, y, x].
    h = np.moveaxis(f.astype(np.float64), 2, 0)
    h -= h.mean()
    del f, levy, metric

    F = np.fft.fft2(h, axes=(1, 2))
    del h
    k1 = 2.0 * np.pi * np.fft.fftfreq(n, d=dx_m)
    KY, KX = np.meshgrid(k1, k1, indexing="ij")
    K = np.hypot(KX, KY)
    cos_wind = np.where(K > 0, KX / np.maximum(K, 1e-30), 0.0)

    # Spreading about the wind AXIS: both half-planes keep equal amplitude
    # here, and the phase below decides which way each mode travels.
    spread = np.abs(cos_wind) ** (2.0 * SPREAD_S)
    spread /= spread[K > 0].mean()
    k_p = 2.0 * np.pi / PEAK_WAVELENGTH_M
    off_axis = np.arccos(np.clip(np.abs(cos_wind), 0.0, 1.0))
    peak = (np.sqrt(1.0 - np.exp(-(K / k_p) ** 4))
            * (1.0 + (PEAK_ENHANCEMENT - 1.0)
               * np.exp(-0.5 * ((K - k_p) / (PEAK_WIDTH * k_p)) ** 2)
               * np.exp(-0.5 * (off_axis / np.radians(PEAK_HEADING_DEG)) ** 2)))
    F *= (np.sqrt(spread) * peak)[None]

    # Dispersion, quantized to the loop. `travel` is odd in k, so the
    # multiplier at -k is the conjugate of the one at k and the field stays
    # real; every mode travels downwind (the upwind half-plane runs its phase
    # the other way, which is the same wave).
    quanta = np.round(np.sqrt(G * K) * period_s / (2.0 * np.pi))
    travel = np.where(cos_wind < 0.0, -1.0, 1.0)
    omega_q = travel * quanta * (2.0 * np.pi / period_s)
    t = np.arange(nt) * dt_s
    F *= np.exp(-1j * omega_q[None] * t[:, None, None])

    slope_x = np.real(np.fft.ifft2(1j * KX[None] * F, axes=(1, 2)))
    slope_y = np.real(np.fft.ifft2(1j * KY[None] * F, axes=(1, 2)))
    scale = RMS_SLOPE / np.sqrt(np.mean(slope_x ** 2 + slope_y ** 2))
    slope_x *= scale
    slope_y *= scale
    F *= scale
    height = np.real(np.fft.ifft2(F, axes=(1, 2)))
    lowpass = np.exp(-0.5 * (K * CREST_LOWPASS_M / (2.0 * np.pi)) ** 2)
    local = height - np.real(np.fft.ifft2(F * lowpass[None], axes=(1, 2)))
    del F

    crest = np.clip(local / (3.0 * local.std()), 0.0, 1.0)

    # Breaking: steep and on a crest; a whitecap leaves foam that decays
    # where it lies while the crest runs on. Two passes round the loop so the
    # trail entering frame 0 is the one leaving the last frame.
    steep = np.hypot(slope_x, slope_y) / RMS_SLOPE
    source = np.clip(steep - BREAKING_SLOPE_RMS, 0.0, None) * (local > 0)
    decay = np.exp(-dt_s / FOAM_DECAY_S)
    intensity = np.empty_like(source)
    trail = np.zeros(source.shape[1:])
    for _ in range(2):
        for k in range(nt):
            trail = np.maximum(source[k], trail * decay)
            intensity[k] = trail
    foam = np.zeros_like(intensity)
    top = int(round(FOAM_MAX_COVERAGE * n * n))
    for k in range(nt):
        flat = intensity[k].ravel()
        if np.count_nonzero(flat) < top:
            raise RuntimeError(
                f"frame {k} has only {np.count_nonzero(flat)} breaking texels, "
                f"fewer than the {top} the foam rank needs; lower "
                "BREAKING_SLOPE_RMS or raise FOAM_DECAY_S.")
        order = np.argsort(flat, kind="stable")[::-1][:top]
        ranked = np.zeros(n * n)
        # Strongest texel -> 1, the top-th -> 1/top: uniform over (0, 1].
        ranked[order] = (top - np.arange(top)) / top
        foam[k] = ranked.reshape(n, n)

    if verbose:
        s = np.hypot(slope_x, slope_y)
        print(f"  sea stats: height std {height.std():.3f} m, "
              f"|slope| p50 {np.median(s):.3f} p99 {np.quantile(s, 0.99):.3f} "
              f"max {s.max():.3f}; breaking source "
              f"{(source > 0).mean() * 100:.2f}% of texels")
    return {
        "slope_x": slope_x.astype(np.float32),
        "slope_y": slope_y.astype(np.float32),
        "foam": foam.astype(np.float32),
        "crest": crest.astype(np.float32),
        "height": height.astype(np.float32),
    }
